#!/usr/bin/env python3
"""Embed shaders/*.glsl into gl3_shaders.h (checked in; no build-time tool).

The module cannot read files from the game VFS at init (the shaders are the
renderer's own data, not game assets chosen by a user), and Android has no
readable source tree, so the GLSL ES 3.20 sources are compiled into the module
as C strings -- exactly how the Vulkan module embeds its SPIR-V.

Run from this directory: python3 embed_shaders.py
Validate the sources first: python3 shaders/validate_glsl.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "gl3_shaders.h")
SHADER_DIR = os.path.join(HERE, "shaders")


def c_escape(text):
    # One C string literal per source line: a raw newline cannot appear inside a
    # string literal, and keeping the line breaks makes the generated header
    # readable/diffable.
    out = []
    for line in text.splitlines():
        line = line.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t")
        out.append(line + "\\n")
    return "".join(out)


def main():
    files = sorted(f for f in os.listdir(SHADER_DIR) if f.endswith(".glsl") or f in ("fog.frag", "color.vert", "color.frag"))
    parts = ["/*\n"
             " * gl3_shaders.h -- GLES 3.2 shader sources for the renderer_gles3 module.\n"
             " *\n"
             " * GENERATED by embed_shaders.py from shaders/*.glsl; do not edit.\n"
             " * The sources are the GLSL ES 3.20 conversions of the Vulkan renderer's\n"
             " * shader templates (see shaders/convert_glsl.py and AUDIT.md), validated by\n"
             " * shaders/validate_glsl.py (139 permutations, glslangValidator ESSL 3.20).\n"
             " */\n"
             "#ifndef GL3_SHADERS_H\n"
             "#define GL3_SHADERS_H\n\n"]

    syms = []
    for f in files:
        sym = "gl3_shader_" + re.sub(r"[^A-Za-z0-9]+", "_", f)
        text = open(os.path.join(SHADER_DIR, f)).read()
        parts.append("static const char %s[] =\n\"%s\";\n\n" % (sym, c_escape(text)))
        syms.append((sym, f))

    parts.append("typedef struct {\n"
                 "\tconst char *name;   // permutation stem (gen_vert, gen_frag, light_vert, ...)\n"
                 "\tconst char *source; // #version 320 es source, defines prepended by the backend\n"
                 "} gl3_shader_source_t;\n\n")
    parts.append("static const gl3_shader_source_t gl3_shader_sources[] = {\n")
    for sym, name in syms:
        parts.append('\t{ "%s", %s },\n' % (name, sym))
    parts.append("};\n")
    parts.append("#define GL3_SHADER_COUNT ((int)( sizeof( gl3_shader_sources ) / sizeof( gl3_shader_sources[0] ) ))\n\n")
    parts.append("#endif // GL3_SHADERS_H\n")

    with open(OUT, "w") as fh:
        fh.write("".join(parts))
    print("wrote", OUT, "from", len(files), "sources")


if __name__ == "__main__":
    main()
